import fs from 'node:fs';
import {buildFocusData} from '../web/focus-model.js';
const read=p=>JSON.parse(fs.readFileSync(p));
const data=buildFocusData(read('web/data/collection.json'),read('web/data/reviewed-exploration.json'));
const routes=data.entities.map(e=>`/${e.type}/${e.id}`);
const rules=['# Generated by scripts/build-routes.mjs. Scoped to historica.online only.','RewriteEngine On','RewriteCond %{HTTPS} !=on','RewriteCond %{HTTP_HOST} ^(?:www\\.)?historica\\.online$ [NC]','RewriteRule ^ https://historica.online%{REQUEST_URI} [R=301,L,NE]','<IfModule mod_headers.c>','  <FilesMatch "\\.(html|js|css|json)$">','    Header set Cache-Control "no-cache, must-revalidate"','  </FilesMatch>','</IfModule>','RewriteCond %{REQUEST_FILENAME} -f [OR]','RewriteCond %{REQUEST_FILENAME} -d','RewriteRule ^ - [L]','RewriteRule ^about/?$ about.html [L]','RewriteRule ^privacy/?$ privacy.html [L]'];
for(const type of ['person','area','state','city','period','event']){
 const ids=data.entities.filter(e=>e.type===type).map(e=>e.id);
 if(ids.some(id=>!/^[-a-z0-9]+$/.test(id)))throw Error('Unsafe route identifier');
 if(ids.length)rules.push(`RewriteRule ^${type}/(${ids.join('|')})/?$ pages/$1.html [L]`);
}
fs.writeFileSync('web/.htaccess',rules.join('\n')+'\n');
fs.writeFileSync('web/data/routes.json',JSON.stringify(routes,null,2)+'\n');
console.log(`Built ${routes.length} focus routes.`);
