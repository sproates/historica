"""Manual, manifest-only upload confined to historica.online. Password stays in memory."""
from deploy_plan import unchanged_paths
import concurrent.futures
import ftplib
import getpass
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import ssl
from datetime import datetime, timezone

config_path = Path(__file__).resolve().parent.parent / '.deploy-local.json'
if not config_path.is_file():
    raise SystemExit('Missing local deployment configuration. See RELEASE.md.')
config = json.loads(config_path.read_text())
if set(config) != {'host', 'username', 'remote_root'}:
    raise SystemExit('Local configuration must contain only host, username and remote_root; never a password.')
HOST, USER, ROOT = (config[key] for key in ('host', 'username', 'remote_root'))
if not all(isinstance(value, str) and value.strip() == value and value for value in (HOST, USER, ROOT)):
    raise SystemExit('Invalid local deployment configuration.')
if not ROOT.startswith('/') or ROOT == '/' or '..' in PurePosixPath(ROOT).parts or ROOT.rstrip('/') != ROOT:
    raise SystemExit('A dedicated absolute remote document root is required.')
local = Path('docs')
manifest = json.loads((local / 'release-manifest.json').read_text())
files = manifest['files'] + [{'path':'release-manifest.json','sha256':hashlib.sha256((local/'release-manifest.json').read_bytes()).hexdigest()}]

def remote(name=''):
    p = PurePosixPath(name)
    if p.is_absolute() or '..' in p.parts:
        raise ValueError('Path outside approved folder')
    return ROOT + ('/' + str(p) if name else '')

for row in files:
    remote(row['path'])
    assert hashlib.sha256((local/row['path']).read_bytes()).hexdigest()==row['sha256'], 'Rebuild changed release assets'
password = getpass.getpass('FTPS password (not saved): ')
ftp = ftplib.FTP_TLS(context=ssl.create_default_context(), timeout=30)
try:
    ftp.connect(HOST,21)
    ftp.auth()
    ftp.login(USER,password)
    ftp.prot_p()
    ftp.set_pasv(True)
    ftp.cwd(ROOT)
    assert ftp.pwd().rstrip('/') == ROOT, 'Unexpected FTP path; stopping'
    # List only the approved directory; never list or inspect the hosting root.
    top = dict(ftp.mlsd(ROOT))
    print('Verified target: '+ROOT, flush=True)
    print('Existing target entries: '+', '.join(sorted(top)), flush=True)
    if 'index.php' in top:
        raise RuntimeError('Existing PHP entry point requires review; nothing uploaded')
    directories = sorted({str(PurePosixPath(r['path']).parent) for r in files} - {'.'})
    listings = {'.': top}
    missing_dirs=[]
    for directory in directories:
        # Current release has only immediate subdirectories.
        assert '/' not in directory, 'Nested directory needs explicit inspection'
        if directory in top:
            assert top[directory].get('type')=='dir', 'Refusing non-directory or symlink target'
            listings[directory] = dict(ftp.mlsd(remote(directory)))
        else:
            missing_dirs.append(directory)
            listings[directory]={}
    backup = Path('release/backups')/datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    backup.mkdir(parents=True)
    record={'host':HOST,'remoteRoot':ROOT,'files':files,'previouslyAbsent':[],'uploaded':[],'verified':[],'unchanged':[]}
    # Compare the completed release manifest once, rather than retrieving every asset.
    if 'release-manifest.json' in top:
        assert top['release-manifest.json'].get('type')=='file'
        previous_bytes=io.BytesIO();ftp.retrbinary('RETR '+remote('release-manifest.json'),previous_bytes.write)
        unchanged=unchanged_paths(files,json.loads(previous_bytes.getvalue()))
        for name in unchanged:
            p=PurePosixPath(name)
            if listings[str(p.parent)].get(p.name,{}).get('type')=='file': record['unchanged'].append(name)
        if previous_bytes.getvalue()==(local/'release-manifest.json').read_bytes():record['unchanged'].append('release-manifest.json')
    print(f"Release delta: {len(files)-len(record['unchanged'])} changed or new files; {len(record['unchanged'])} unchanged.",flush=True)
    # Complete replacement backups before any remote write.
    for row in files:
        name=row['path']; p=PurePosixPath(name)
        if name in record['unchanged']:continue
        existing=listings[str(p.parent)].get(p.name)
        if existing:
            assert existing.get('type')=='file', 'Refusing non-regular existing file'
            content=io.BytesIO();ftp.retrbinary('RETR '+remote(name),content.write)
            if name=='.htaccess' and content.getvalue()!=(local/name).read_bytes() and not content.getvalue().startswith(b'# Generated by scripts/build-routes.mjs.'):
                raise RuntimeError('Existing domain routing requires review before replacement')
            if hashlib.sha256(content.getvalue()).hexdigest()==row['sha256']:record['unchanged'].append(name)
            target=backup/name;target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(content.getvalue())
        else: record['previouslyAbsent'].append(name)
    (backup/'deployment.json').write_text(json.dumps(record,indent=2))
    print('Backups complete: '+str(backup),flush=True)
    for directory in missing_dirs: ftp.mkd(remote(directory))
    ordered=sorted(files,key=lambda r:(r['path']=='release-manifest.json',r['path']=='index.html',r['path']=='.htaccess',r['path'].endswith('.html'),r['path']))
    def upload(connection, row):
        name=row['path']
        with (local/name).open('rb') as source: connection.storbinary('STOR '+remote(name),source)
        content=io.BytesIO();connection.retrbinary('RETR '+remote(name),content.write)
        assert hashlib.sha256(content.getvalue()).hexdigest()==row['sha256'], 'Remote bytes differ: '+name
        return name

    def save_uploaded(name):
        record['uploaded'].append(name)
        record['verified'].append(name)
        (backup/'deployment.json').write_text(json.dumps(record,indent=2))

    # Independent generated pages can transfer together, before routing changes.
    page_rows=[r for r in ordered if r['path'].startswith('pages/') and r['path'] not in record['unchanged']]
    def upload_batch(rows):
        connection=ftplib.FTP_TLS(context=ssl.create_default_context(),timeout=30)
        completed=[]
        try:
            connection.connect(HOST,21);connection.auth();connection.login(USER,password)
            connection.prot_p();connection.set_pasv(True);connection.cwd(ROOT)
            assert connection.pwd().rstrip('/')==ROOT
            for row in rows: completed.append(upload(connection,row))
            return completed
        finally: connection.close()
    if page_rows:
        print(f'Uploading {len(page_rows)} history pages across four verified FTPS connections.',flush=True)
        with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
            futures=[pool.submit(upload_batch,page_rows[i::4]) for i in range(4) if page_rows[i::4]]
            for future in concurrent.futures.as_completed(futures):
                for name in future.result(): save_uploaded(name)
                print(f"Verified {len(record['verified'])}/{len(page_rows)} history pages.",flush=True)
    for row in ordered:
        name=row['path']
        if name in record['unchanged'] or name in record['verified']:continue
        save_uploaded(upload(ftp,row))
        print('Uploaded and verified: '+name,flush=True)
    print('FTPS deployment complete. No operations outside '+ROOT,flush=True)
finally:
    password=None
    ftp.close()
