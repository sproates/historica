import fs from 'node:fs';
import {spawnSync} from 'node:child_process';

// Recreate this owned output directory so renamed/deleted sources leave no stale modules.
fs.rmSync('web/generated',{recursive:true,force:true});
const result=spawnSync(process.execPath,['node_modules/typescript/bin/tsc','-p','tsconfig.json'],{stdio:'inherit'});
if(result.status!==0)process.exit(result.status??1);
const {readHistoryPacks,readPrototypeData}=await import('./lib/history-content.mjs');
const prototype=readPrototypeData(readHistoryPacks());
fs.writeFileSync('web/generated/content/prototype-data.js','// Generated by scripts/build-client.mjs. Edit content/ instead.\nexport default '+JSON.stringify(prototype,null,2)+';\n');
